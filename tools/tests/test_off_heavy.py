class HeavyRefusalTest(unittest.TestCase):
    def test_accepts_test_build_lint_and_typecheck_runners(self) -> None:
        for command in ACCEPTED:
            with self.subTest(command=command):
                self.assertIsNone(refusal(command))

    def test_refuses_everything_else(self) -> None:
        for command in REFUSED:
            with self.subTest(command=command):
                self.assertIsNotNone(refusal(command))


if __name__ == "__main__":
    unittest.main()
